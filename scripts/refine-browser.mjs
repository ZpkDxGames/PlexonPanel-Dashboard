import { spawn } from "node:child_process";
import { chromium } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { writeFile, mkdir } from "node:fs/promises";
const server = spawn(
  process.execPath,
  ["node_modules/vite/bin/vite.js", "--host", "127.0.0.1", "--port", "4191"],
  { stdio: "ignore" },
);
for (let i = 0; i < 100; i++) {
  try {
    if ((await fetch("http://127.0.0.1:4191")).ok) break;
  } catch {}
  await new Promise((r) => setTimeout(r, 200));
}
const b = await chromium.launch({
  executablePath: process.env.PLEXON_CHROMIUM,
  args: [
    "--no-sandbox",
    "--no-zygote",
    "--disable-dev-shm-usage",
    "--use-gl=angle",
    "--use-angle=swiftshader",
    "--enable-unsafe-swiftshader",
  ],
});
const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } }),
  p = await ctx.newPage(),
  checks = [];
const check = (name, pass, details = "") => {
  checks.push({ name, pass, details });
  console.log(name, pass, details);
  if (!pass) throw new Error(name + ": " + details);
};
p.setDefaultTimeout(15000);
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
try {
  await p.addInitScript(() =>
    localStorage.setItem(
      "plexon:preferences",
      JSON.stringify({ theme: "light", skinProvider: "auto" }),
    ),
  );
  let providerRequests = [];
  await p.route(/https:\/\/(crafatar|mc-heads|minotar)/, async (r) => {
    providerRequests.push(r.request().url());
    if (r.request().url().includes("mc-heads")) return r.abort();
    return r.fulfill({
      contentType: "image/svg+xml",
      body: '<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><path fill="#b88753" d="M0 0h64v64H0z"/></svg>',
    });
  });
  await p.goto("http://127.0.0.1:4191/?demo=1#Performance");
  await p.locator(".time-series").first().waitFor();
  await p.waitForTimeout(1300);
  check(
    "Removed pages leave navigation",
    !(await p.getByRole("button", { name: "Files", exact: true }).count()) &&
      !(await p.getByRole("button", { name: "Plugins", exact: true }).count()),
  );
  await p.locator(".time-series").first().hover();
  check(
    "Hover is local to one chart",
    (await p.locator(".chart-tooltip").count()) === 1,
  );
  await p.mouse.move(0, 0);
  await p.evaluate(() => (location.hash = "Players"));
  await p.waitForTimeout(1200);
  check(
    "Skin provider fallback loads an image response (stubbed providers)",
    (await p
      .locator(".player-head img")
      .first()
      .evaluate((e) => e.complete && e.naturalWidth > 0)) &&
      providerRequests.some((s) => s.includes("minotar")),
  );
  await p.evaluate(() => (location.hash = "Settings"));
  await p.getByRole("combobox", { name: "Graph format" }).waitFor();
  await p.getByRole("combobox", { name: "Graph format" }).focus();
  await p.keyboard.press("ArrowDown");
  await p.keyboard.press("Enter");
  check(
    "Custom dropdown keyboard selection",
    (await p.evaluate(
      () => JSON.parse(localStorage.getItem("plexon:preferences")).chartStyle,
    )) === "line",
  );
  await p.getByRole("combobox", { name: "Interface accent" }).click();
  await p.getByRole("option", { name: "Teal", exact: true }).click();
  check(
    "Accent applies",
    (await p.locator("html").getAttribute("data-accent")) === "teal",
  );
  const axe = await new AxeBuilder({ page: p }).analyze();
  check(
    "Settings including custom dropdowns has no axe violations",
    axe.violations.length === 0,
    JSON.stringify(
      axe.violations.map((v) => ({
        id: v.id,
        nodes: v.nodes.map((n) => n.target),
      })),
    ),
  );
  // Real PNG generated by browser canvas, kept per selected instance.
  const data = await p.evaluate(() => {
    const c = document.createElement("canvas");
    c.width = c.height = 64;
    c.getContext("2d").fillRect(0, 0, 64, 64);
    return c.toDataURL("image/png").split(",")[1];
  });
  await p.getByLabel("Choose a 64 × 64 PNG").setInputFiles({
    name: "server-icon.png",
    mimeType: "image/png",
    buffer: Buffer.from(data, "base64"),
  });
  await p.waitForTimeout(200);
  check(
    "Selected server icon replaces panel logo",
    (await p.locator(".brand img.server-art").count()) === 1,
  );
  await p.evaluate(() => (location.hash = "Overview"));
  await p.locator(".kpi-value").first().waitFor();
  await p.mouse.move(0, 0);
  await p.waitForTimeout(1000);
  const transition = await p.evaluate(async () => {
    const { session } = await import("/src/adapter/session.ts");
    const snap = session.getSnapshot();
    const chart = document.querySelector(".time-series");
    const grid = () =>
      [...chart.querySelectorAll("text")]
        .slice(0, 5)
        .map((e) => e.textContent)
        .join(",");
    const axisBefore = grid();
    const line = chart.querySelector(".chart-line");
    const before = line.getAttribute("d");
    const start = performance.now();
    session.receiveFixture({
      type: "server.event",
      serverId: snap.state.serverId,
      agentKind: "PAPER",
      agentSession: "fixture-paper",
      eventType: "telemetry.server",
      body: {
        ...snap.state.server,
        capturedAt: new Date().toISOString(),
        tps: [19.9, 19.9, 19.9],
      },
    });
    const frames = [];
    let endpointError = 0;
    for (let i = 0; i < 12; i++) {
      await new Promise((r) => setTimeout(r, 35));
      const coordinates = (
        line.getAttribute("d").match(/-?\d+(?:\.\d+)?/g) ?? []
      ).map(Number);
      const dot = chart.querySelector(".chart-end");
      endpointError = Math.max(
        endpointError,
        Math.hypot(
          Number(dot.getAttribute("cx")) - coordinates.at(-2),
          Number(dot.getAttribute("cy")) - coordinates.at(-1),
        ),
      );
      frames.push({
        path: line.getAttribute("d"),
        at: performance.now() - start,
      });
    }
    return {
      endpointError,
      axisBefore,
      axisAfter: grid(),
      distinct: new Set(frames.map((f) => f.path)).size,
      firstChange: frames.find((f) => f.path !== before)?.at ?? -1,
      elapsed: performance.now() - start,
      wrapperAnimations: chart.querySelector("g[clip-path] g").getAnimations()
        .length,
    };
  });
  check(
    "Live geometry changes smoothly without wrapper restart",
    transition.distinct > 2 && transition.wrapperAnimations === 0,
    JSON.stringify(transition),
  );
  check(
    "Live point follows the interpolated line",
    transition.endpointError < 0.05,
    JSON.stringify(transition),
  );
  check(
    "Small telemetry changes do not rescale axes",
    transition.axisBefore === transition.axisAfter,
    JSON.stringify(transition),
  );
  check(
    "Default display buffering responds in under 500ms",
    transition.firstChange >= 0 && transition.firstChange < 500,
    JSON.stringify(transition),
  );
  await p.evaluate(() => (location.hash = "Logs"));
  await p.getByRole("heading", { name: "Server activity" }).waitFor();
  check(
    "Activity replaces duplicated console",
    !(await p.locator(".virtual-log").count()),
  );
  await p.evaluate(async () => {
    const { session } = await import("/src/adapter/session.ts");
    const { makeFixture, fixtureAction } =
      await import("/src/development/fixtures.ts");
    const state = makeFixture("healthy");
    state.console = [
      { id: "join", level: "INFO", content: "LumaCraft joined the game" },
      {
        id: "world",
        level: "ERROR",
        content: "World generation failed for chunk 0,0",
      },
      {
        id: "backup",
        level: "ERROR",
        content: "Backup remote verification failed",
      },
      { id: "normal", level: "INFO", content: "Ordinary debug report" },
      {
        id: "chat",
        level: "INFO",
        content: "<LumaCraft> chat stays in Console",
      },
    ];
    session.installFixture("activity-check", state, fixtureAction);
  });
  await p.waitForTimeout(300);
  check(
    "Activity excludes ordinary output and chat",
    (await p.locator(".event-row").count()) === 3,
  );
  await p
    .getByRole("button", { name: "World generation", exact: true })
    .click();
  check(
    "Activity filters world generation incidents",
    (await p.locator(".event-row").count()) === 1 &&
      (await p.locator(".event-row").textContent()).includes(
        "World generation failed",
      ),
  );
  await p.evaluate(async () => {
    const { session } = await import("/src/adapter/session.ts");
    const { makeFixture, fixtureAction } =
      await import("/src/development/fixtures.ts");
    const state = makeFixture("healthy");
    state.serverId = "other-instance";
    state.ready.serverId = "other-instance";
    session.installFixture("isolated-icon", state, fixtureAction);
  });
  await p.waitForTimeout(300);
  check(
    "Selected server icons cannot cross instance boundaries",
    (await p.locator(".brand img.server-art").count()) === 0,
  );
  check("No runtime errors", errors.length === 0, JSON.stringify(errors));
} finally {
  server.kill();
  await mkdir("docs/revamp/refinement", { recursive: true });
  await writeFile(
    "docs/revamp/refinement/interactions.json",
    JSON.stringify(checks, null, 2),
  );
  await b.close();
  console.log(JSON.stringify(checks, null, 2));
}
